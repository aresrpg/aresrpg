// Preserve the approved source and generate its gameplay integration offline.
import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { resolve } from 'node:path'
import { runInNewContext } from 'node:vm'

import { compile_spell_shader } from './spell_shader.mjs'
import { compile_spell_wgsl } from './spell_wgsl.mjs'

const root = resolve(import.meta.dirname, '..')
const source = readFileSync(resolve(root, 'seed/content/spell_effects/source.html'), 'utf8')
const synth = readFileSync(resolve(root, 'seed/content/spell_effects/synth.js'), 'utf8')
const section = (start, end) => {
  const offset = source.indexOf(start)
  if (offset < 0) throw new Error(`Missing source boundary: ${start}`)
  const until = source.indexOf(end, offset + start.length)
  if (until < 0) throw new Error(`Missing source boundary: ${end}`)
  return source.slice(offset, until)
}
const catalog = section('const EL =', 'const CLASS_NAME =')
const class_ids = section('const NEW_CLASS =', '\n\n')
const shader = section('const FRAG = `', '`;').slice('const FRAG = `'.length)
const flight = section('const add = (a, b, k = 1)', 'const sync =')
const sounds = section('const TRAP_WAIT =', 'const play_spell =')
const playback = section('const play_spell =', '// ---------------- stage')
const clock = section('const IMPACT_SPEED =', '\n\n')
const trap_clock = section('const TRAP_WAIT =', 'const LEAD =')
const draw = section('  const draw = time => {', '\n  const frame =')
const audio = section('const A = { on:', '// seconds of lead-in')
const recording_decode =
  "const bytes = Uint8Array.from(atob(b64), ch => ch.charCodeAt(0));\n    A.s['d_' + name] = await ctx.decodeAudioData(bytes.buffer);"
if (audio.split(recording_decode).length !== 2) throw new Error('Authored recording decode boundary changed')
const byte_audio = audio.replace(recording_decode, "A.s['d_' + name] = await ctx.decodeAudioData(b64);")
const hash = createHash('sha256').update(source).digest('hex')
const header = `// Generated by scripts/generate_spell_effects.mjs; do not edit.\n// Approved source SHA-256: ${hash}\n`
const program = `${header}
export const SOURCE_SHA256 = ${JSON.stringify(hash)};
export const create_source = () => {
${catalog}
${class_ids}
${clock}
${flight}
${sounds}
let selected_class = 'yogan';
const state = { spell: 0, clock: 0, cycle: 0 };
const spells = () => CLASSES[selected_class];
let devicePixelRatio = 1, reduced = false;
const stage = { clientWidth: 1, clientHeight: 1, width: 1, height: 1 };
const values = {};
const gl = {
 viewport: () => {}, drawArrays: () => {}, TRIANGLES: 4,
 uniform1f: (name, value) => { values[name] = value; },
 uniform1i: (name, value) => { values[name] = value; },
 uniform2f: (name, x, y) => { values[name] = [x, y]; },
 uniform3fv: (name, value) => { values[name] = [...value]; },
};
const U = name => name;
const $ = () => ({ classList: { toggle: () => {} } });
const A = { on: false, ready: false };
const play_spell = () => {};
${draw}
return {
 catalog: CLASSES, palettes: EL, tokens: TOK, lead: LEAD, hold: HOLD, impact_speed: IMPACT_SPEED, trap_wait: TRAP_WAIT,
 select: (classe, name, overrides = {}) => {
  selected_class = classe;
  state.spell = CLASSES[classe].findIndex(spell => spell.name === name);
  if (state.spell < 0) throw new Error('Unknown authored spell: ' + name);
  const row = spells()[state.spell];
  Object.assign(row, finish(classe)({ ...row, ...overrides }, state.spell));
  return { ...row };
 },
 frame: (time, width, height, pixel_ratio = 1, reduce_motion = false) => {
  state.clock = time; stage.clientWidth = width; stage.clientHeight = height;
  devicePixelRatio = pixel_ratio; reduced = reduce_motion;
  draw(time);
  return { ...values };
 },
 sound_plan: () => sound_plan(spells()[state.spell]),
};
};
`
const audio_program = `${header}
export const create_audio_source = (DOFUS, LEAD_AUTO, LEAD, sound_plan, synthesis) => {
${clock}
${trap_clock}
const SR = synthesis.sample_rate;
const synth_all = () => synthesis.samples;
${byte_audio}
${playback}
return { A, boot_audio, play_spell, fresh_bus };
};
`
const synth_program = `${header}
export const synthesize_spell_audio = () => {
${synth}
return { sample_rate: SR, samples: synth_all() };
};
`
const write_artifact = (directory, name, text) => {
  const path = resolve(root, directory, name)
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== text) throw new Error(`Stale authored spell program: ${name}`)
  } else writeFileSync(path, text)
}

const catalog_json = JSON.stringify(runInNewContext(catalog + '\nCLASSES'), null, 2) + '\n'
for (const [name, text] of [
  ['claude_spell_source.js', program],
  [
    'claude_spell_wgsl.js',
    `${header}export const SPELL_SHADER = ${JSON.stringify(compile_spell_wgsl(compile_spell_shader(shader)))};\n`,
  ],
  ['claude_spell_audio.js', audio_program],
  ['claude_spell_synth.js', synth_program],
  ['claude_spell_catalog.json', catalog_json],
]) {
  write_artifact('packages/engine/src/generated', name, text)
}
write_artifact(
  'packages/engine/test/fixtures',
  'claude_spell_fragment.json',
  JSON.stringify({ source_sha256: hash, fragment: shader }, null, 2) + '\n'
)

console.log(`Exact spell-source extraction verified: ${hash.slice(0, 12)}`)
