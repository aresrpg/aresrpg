import { expect, test } from '@playwright/test'

test('sell filters retain their selection across dialog cancellation and list the reviewed lot', async ({ page }) => {
  await page.goto('/e2e/fixtures/marketplace.html?sell')
  const inventory = page.getByRole('region', { name: 'Inventory', exact: true })
  const listings = page.getByRole('region', { name: 'Your listings', exact: true })
  await expect(listings.locator('[data-marketplace-own-listing]')).toHaveCount(3)
  await page.screenshot({ path: 'test-results/marketplace-sell-desktop.png' })
  await listings.getByRole('combobox').selectOption('RESOURCES')
  await expect(listings.locator('[data-marketplace-own-listing]')).toHaveCount(1)
  await listings.getByRole('searchbox').fill('no-such-item')
  await expect(listings).toContainText('No matches')
  await listings.getByRole('searchbox').fill('')
  await inventory.getByRole('button', { name: 'Resources', exact: true }).click()
  await expect(inventory.locator('[data-marketplace-owned-item]')).toHaveCount(3)
  await inventory.locator('[data-marketplace-owned-item="sell-1"]').click()
  const dialog = page.getByRole('dialog', { name: 'List for sale', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'List for sale', exact: true })).toBeDisabled()
  await dialog.getByLabel('Total price for the lot').fill('-1')
  await expect(dialog.getByRole('button', { name: 'List for sale', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).last().click()
  await expect(dialog).toHaveCount(0)
  await expect(inventory.getByRole('button', { name: 'Resources', exact: true })).toHaveAttribute(
    'aria-pressed',
    'true'
  )
  await inventory.locator('[data-marketplace-owned-item="sell-1"]').click()
  await dialog.getByRole('button', { name: '×100', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '×100', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await dialog.getByLabel('Total price for the lot').fill('2.5')
  await dialog.getByRole('button', { name: 'List for sale', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const listed = listings.locator('[data-marketplace-own-listing="sell-1"]')
  await expect(listed).toContainText('×100')
  await expect(listed).toContainText('2.50')
  await expect(inventory.locator('[data-marketplace-owned-item="sell-1"]')).toHaveCount(0)
})

test('sell dialog preserves exact rolled stats and fits a narrow window', async ({ page }) => {
  await page.setViewportSize({ width: 720, height: 600 })
  await page.goto('/e2e/fixtures/marketplace.html?sell')
  await page.locator('[data-marketplace-owned-item="sell-0"]').click()
  const dialog = page.getByRole('dialog', { name: 'List for sale', exact: true })
  await expect(dialog).toContainText('+27')
  await expect(dialog.locator('[data-sale-scroll] > div')).toHaveCSS('background-color', 'rgb(36, 42, 51)')
  await page.screenshot({ path: 'test-results/marketplace-sale-dialog.png' })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.mouse.move(0, 0)
  await page.locator('h3').first().click()
  await page.screenshot({ path: 'test-results/marketplace-sell-narrow.png' })
})

test('matching lots expand cheapest first and delist only the chosen object', async ({ page }) => {
  await page.goto('/e2e/fixtures/marketplace.html?sell&stacks')
  const stack = page.locator('[data-marketplace-stack]')
  await expect(stack).not.toHaveAttribute('open', '')
  const scroll = page.locator('.market-own-listings-scroll')
  const height = await scroll.evaluate((element) => element.scrollHeight)
  await stack.locator('summary').hover()
  await expect(stack).toHaveAttribute('open', '')
  expect(await scroll.evaluate((element) => element.scrollHeight)).toBe(height)
  const rows = stack.locator('[data-marketplace-own-listing]')
  await expect(rows).toHaveCount(3)
  await expect(rows.first()).toHaveAttribute('data-marketplace-own-listing', 'cheap')
  await expect(rows.last()).toHaveAttribute('data-marketplace-own-listing', 'expensive')
  await rows.nth(1).getByRole('button', { name: 'Delist', exact: true }).click()
  await expect(rows).toHaveCount(2)
  await expect(rows.first()).toHaveAttribute('data-marketplace-own-listing', 'cheap')
  await expect(rows.last()).toHaveAttribute('data-marketplace-own-listing', 'expensive')
  await page.getByRole('heading', { name: 'Your listings' }).click()
  await expect(stack).not.toHaveAttribute('open', '')
  await stack.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(stack).toHaveAttribute('open', '')
  await expect(stack.locator('.market-stack-listings')).toBeVisible()
  await expect(rows.first()).toBeVisible()
  await page.screenshot({ path: 'test-results/marketplace-expanded-stack.png' })
})
